// GLB street buildings -> components/delivery/three/building-models.ts
// usage: node scripts/convert-buildings.mjs <main 01..05 glb ...> <sub 01..05 glb ...>
// Applies each node's scale/translation, welds positions to int16 (1/2048 m),
// keeps one palette colour (material baseColor, sRGB) per triangle and drops
// exact duplicate triangles (coplanar copies flicker as z-fighting).
import fs from "node:fs";
import path from "node:path";

const toSrgb = c => c <= .0031308 ? c * 12.92 : 1.055 * c ** (1 / 2.4) - .055;
const hex = f => "#" + f.slice(0, 3).map(c => Math.round(toSrgb(c) * 255).toString(16).padStart(2, "0")).join("");
const SIZES = { 5121: 1, 5123: 2, 5125: 4, 5126: 4 };

function read(file) {
  const b = fs.readFileSync(file), jsonLength = b.readUInt32LE(12);
  const json = JSON.parse(b.subarray(20, 20 + jsonLength).toString());
  const bin = b.subarray(28 + jsonLength);
  const accessor = i => {
    const a = json.accessors[i], view = json.bufferViews[a.bufferView], n = { SCALAR: 1, VEC3: 3, VEC4: 4 }[a.type];
    const size = SIZES[a.componentType], stride = view.byteStride || size * n, start = (view.byteOffset || 0) + (a.byteOffset || 0);
    const get = { 5121: "readUInt8", 5123: "readUInt16LE", 5125: "readUInt32LE", 5126: "readFloatLE" }[a.componentType];
    return Array.from({ length: a.count * n }, (_, k) => bin[get](start + Math.floor(k / n) * stride + (k % n) * size));
  };
  return { json, accessor };
}

function convert(file) {
  const { json, accessor } = read(file);
  const palette = [], colors = [], verts = new Map(), positions = [], indices = [], seen = new Set();
  const vertex = (x, y, z) => {
    const q = [x, y, z].map(v => Math.round(v * 2048));
    if (q.some(v => Math.abs(v) > 32767)) throw new Error(`${file}: coordinate beyond int16 (${x}, ${y}, ${z})`);
    const key = q.join();
    if (!verts.has(key)) { verts.set(key, verts.size); positions.push(...q); }
    return verts.get(key);
  };
  for (const node of json.nodes.filter(n => n.mesh != null)) {
    if (node.rotation || node.matrix) throw new Error(`${file}: rotated nodes are not supported`);
    const s = node.scale || [1, 1, 1], t = node.translation || [0, 0, 0];
    for (const p of json.meshes[node.mesh].primitives) {
      if ((p.mode ?? 4) !== 4) throw new Error(`${file}: only triangle lists are supported`);
      const pos = accessor(p.attributes.POSITION), idx = p.indices != null ? accessor(p.indices) : pos.map((_, k) => k).filter(k => k < pos.length / 3);
      const color = hex(json.materials?.[p.material]?.pbrMetallicRoughness?.baseColorFactor ?? [1, 1, 1, 1]);
      if (!palette.includes(color)) palette.push(color);
      for (let k = 0; k < idx.length; k += 3) {
        const tri = [0, 1, 2].map(o => { const v = idx[k + o] * 3; return vertex(pos[v] * s[0] + t[0], pos[v + 1] * s[1] + t[1], pos[v + 2] * s[2] + t[2]); });
        if (new Set(tri).size < 3) continue;
        const key = [...tri].sort((a, b) => a - b).join();
        if (seen.has(key)) continue;
        seen.add(key); indices.push(...tri); colors.push(palette.indexOf(color));
      }
    }
  }
  if (verts.size > 65535 || palette.length > 256) throw new Error(`${file}: too many vertices or colours`);
  // Re-centre x/z on the footprint so origin = base centre (some exports are off-centre).
  for (const a of [0, 2]) {
    const v = positions.filter((_, k) => k % 3 === a), mid = Math.round((Math.max(...v) + Math.min(...v)) / 2);
    for (let k = a; k < positions.length; k += 3) positions[k] -= mid;
  }
  const axis = a => { const v = positions.filter((_, k) => k % 3 === a); return (Math.max(...v) - Math.min(...v)) / 2048; };
  const b64 = arr => Buffer.from(arr.buffer).toString("base64");
  return {
    name: path.basename(file).replace(/( \(\d+\))?\.glb$/, ""), w: +axis(0).toFixed(3), h: +axis(1).toFixed(3), d: +axis(2).toFixed(3), palette,
    positions: b64(Int16Array.from(positions)), indices: b64(Uint16Array.from(indices)), colors: b64(Uint8Array.from(colors)), triangles: colors.length,
  };
}

const models = process.argv.slice(2).map(convert);
for (const m of models) console.log(m.name, m.w, m.h, m.d, `${m.triangles} tris`, `${m.palette.length} colours`);
const out = `// Generated by scripts/convert-buildings.mjs from the street building GLBs: 0-4 main (v4), 5-9 colourful sub.
// Welded int16 positions (1/2048 m), triangle indices and one palette colour per triangle.
// Origin = base centre, front = +Z.
export const BUILDING_MODELS = [
${models.map(m => `  { name: ${JSON.stringify(m.name)}, w: ${m.w}, h: ${m.h}, d: ${m.d},
    palette: ${JSON.stringify(m.palette)},
    positions: "${m.positions}",
    indices: "${m.indices}",
    colors: "${m.colors}" },`).join("\n")}
] as const;
`;
fs.writeFileSync(new URL("../components/delivery/three/building-models.ts", import.meta.url), out);
