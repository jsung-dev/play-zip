// Prop/house/obstacle GLBs -> components/delivery/three/asset-models.ts
// usage: node scripts/convert-assets.mjs <glb ...>   (every asset in use, each run rewrites the file)
// Each mesh node becomes a part (local int16 positions at 1/2048 m, its translation kept as the pivot);
// every named node's translation is also an anchor (door, sign, ...). Exact duplicate triangles are dropped.
import fs from "node:fs";
import path from "node:path";
import { readGlb, primitiveTriangles } from "./glb-read.mjs";

function convert(file) {
  const { json, accessor } = readGlb(file);
  const parts = [], anchors = {};
  const visit = (index, offset) => {
    const node = json.nodes[index];
    if (node.rotation || node.matrix || node.scale) throw new Error(`${file}: node ${node.name} has rotation/scale`);
    const t = (node.translation ?? [0, 0, 0]).map((v, a) => v + offset[a]);
    if (node.name && node.name !== "root") anchors[node.name] = t.map(v => +v.toFixed(4));
    if (node.mesh != null) {
      const palette = [], colors = [], verts = new Map(), positions = [], indices = [], seen = new Set();
      for (const p of json.meshes[node.mesh].primitives) for (const tri of primitiveTriangles(file, json, accessor, p, v => v)) {
        if (!palette.includes(tri.color)) palette.push(tri.color);
        const ids = tri.pos.map(v => {
          const q = v.map(c => Math.round(c * 2048));
          if (q.some(c => Math.abs(c) > 32767)) throw new Error(`${file}: coordinate beyond int16`);
          const key = q.join();
          if (!verts.has(key)) { verts.set(key, verts.size); positions.push(...q); }
          return verts.get(key);
        });
        const key = [...ids].sort((a, b) => a - b).join();
        if (new Set(ids).size < 3 || seen.has(key)) continue;
        seen.add(key); indices.push(...ids); colors.push(palette.indexOf(tri.color));
      }
      if (verts.size > 65535 || palette.length > 256) throw new Error(`${file}: too many vertices or colours`);
      const b64 = arr => Buffer.from(arr.buffer).toString("base64");
      parts.push({ name: node.name, t, palette, positions: b64(Int16Array.from(positions)), indices: b64(Uint16Array.from(indices)), colors: b64(Uint8Array.from(colors)), triangles: colors.length });
    }
    for (const child of node.children ?? []) visit(child, t);
  };
  for (const root of json.scenes[json.scene ?? 0].nodes) visit(root, [0, 0, 0]);
  return { name: path.basename(file, ".glb"), parts, anchors };
}

const models = process.argv.slice(2).map(convert);
for (const m of models) console.log(m.name, m.parts.map(p => `${p.name}:${p.triangles}`).join(" "));
const out = `// Generated by scripts/convert-assets.mjs from the delivery_game_assets GLBs (v5; rider, bus, destination v6).
// Per part: pivot t, welded int16 positions (1/2048 m, local to t), triangle indices, one palette colour per triangle.
// Origin = base centre, front = +Z. anchors = every named node's position (door, sign, ...).
export const ASSET_MODELS = {
${models.map(m => `  ${JSON.stringify(m.name)}: {
    anchors: ${JSON.stringify(m.anchors)},
    parts: [
${m.parts.map(p => `      { name: ${JSON.stringify(p.name)}, t: ${JSON.stringify(p.t)}, palette: ${JSON.stringify(p.palette)},
        positions: "${p.positions}",
        indices: "${p.indices}",
        colors: "${p.colors}" },`).join("\n")}
    ],
  },`).join("\n")}
} as const;
export type AssetName = keyof typeof ASSET_MODELS;
`;
fs.writeFileSync(new URL("../components/delivery/three/asset-models.ts", import.meta.url), out);
